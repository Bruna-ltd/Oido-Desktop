//! Remote MCP servers worth offering as one click: the name and address are filled in, and the
//! person adds it themselves. Nothing here starts a program, and nothing is registered until the
//! person presses Add. This is Studio's list (the ones with a fixed address that speak streamable
//! HTTP), with its logos: pictures under `assets/mcp/`, or the brand's mark where Studio draws one.

use super::Auth;

/// How a server is pictured.
#[derive(Clone, Copy, Debug)]
pub enum Logo {
    /// A PNG or JPEG, square.
    Image(&'static [u8]),
    /// The brand's mark: a path in a 24 x 24 box, in the brand's colour, drawn on a white tile.
    Mark {
        color: &'static str,
        path: &'static str,
    },
}

#[derive(Clone, Copy, Debug)]
pub struct Preset {
    pub name: &'static str,
    pub url: &'static str,
    pub description: &'static str,
    pub auth: Auth,
    pub logo: Logo,
}

const fn preset(
    name: &'static str,
    url: &'static str,
    description: &'static str,
    auth: Auth,
    logo: Logo,
) -> Preset {
    Preset {
        name,
        url,
        description,
        auth,
        logo,
    }
}

/// The picture of the server at `url`, when it is one of the presets.
pub fn logo_for(url: &str) -> Option<(&'static str, Logo)> {
    PRESETS
        .iter()
        .find(|p| p.url == url)
        .map(|p| (p.name, p.logo))
}

